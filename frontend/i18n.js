let flameLang = "en";
try {
  const saved = localStorage.getItem("flameid-lang");
  if (FLAMEID_LANGS.includes(saved)) flameLang = saved;
} catch (e) { /* private mode — stay on English */ }

function t(key, params) {
  let s = (I18N_DICT[flameLang] && I18N_DICT[flameLang][key]) ?? I18N_DICT.en[key] ?? key;
  if (params) {
    for (const k in params) s = s.replaceAll("{" + k + "}", String(params[k]));
  }
  return s;
}

function applyI18n() {
  document.documentElement.lang = flameLang === "zh" ? "zh-CN" : flameLang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  // data-i18n-html: dictionary value may contain <b>/<code> markup.
  // Values are hardcoded in this file only — never user input.
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  document.querySelectorAll("[data-lang]").forEach((btn) => {
    const active = btn.dataset.lang === flameLang;
    btn.classList.toggle("active", active);
    btn.setAttribute("aria-pressed", active ? "true" : "false");
  });
}

function setLang(lang) {
  if (!FLAMEID_LANGS.includes(lang) || lang === flameLang) return;
  flameLang = lang;
  try { localStorage.setItem("flameid-lang", lang); } catch (e) { /* ignore */ }
  applyI18n();
  document.dispatchEvent(new CustomEvent("flameid-lang", { detail: { lang } }));
}

document.addEventListener("click", (e) => {
  const btn = e.target.closest("[data-lang]");
  if (btn) setLang(btn.dataset.lang);
});

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", applyI18n);
} else {
  applyI18n();
}

window.FlameI18n = {
  t,
  setLang,
  applyI18n,
  get lang() { return flameLang; },
};
